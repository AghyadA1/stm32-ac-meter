/**
 * @file    app.c
 * @brief   Input -> processing -> output for the STM32 AC meter.
 *
 * Input   TIM3 (3333.33 Hz) triggers ADC1. The ADC interrupt alternates
 *         between channel 1 (PA1, voltage) and channel 2 (PA2, current), one
 *         channel per conversion, and feeds each sample to acmeter.c.
 *         A push button (PA7, EXTI, falling edge) changes the shown quantity.
 * Output  TIM2 (180 Hz) multiplexes the 3-digit display.
 *         TIM4 CH2 (PB7, 2 kHz PWM) drives the push-pull -12 V generator.
 */
#include "app.h"

#include <math.h>
#include <stdbool.h>

#include "main.h"
#include "acmeter.h"
#include "display.h"

/* Handles generated by STM32CubeMX in main.c */
extern ADC_HandleTypeDef hadc1;
extern TIM_HandleTypeDef htim2;
extern TIM_HandleTypeDef htim3;
extern TIM_HandleTypeDef htim4;

/* What the display shows (button cycles through these) */
enum {
    SHOW_VRMS = 0,   /* Vrms  x10   ->  e.g. 230 = 23.0 V  */
    SHOW_IRMS,       /* Irms  x100  ->  e.g. 115 = 1.15 A  */
    SHOW_FREQ,       /* f     x1    ->  e.g.  50 = 50 Hz   */
    SHOW_PF,         /* |cos φ| x100 -> e.g.  60 = 0.60    */
    SHOW_P,          /* P     x100  (W)                    */
    SHOW_Q,          /* Q     x100  (VAR)                  */
    SHOW_S,          /* S     x100  (VA)                   */
    SHOW_COUNT
};

/* ADC channel switching */
static ADC_ChannelConfTypeDef sConfig = {0};
static uint32_t raw_value = 0;
static int      c = 0;            /* 0: voltage sample, 1: current sample */

/* Display timing (counted in TIM2 ticks of ~5.5 ms) */
static volatile int count  = 0;   /* shows the mode number for ~1.1 s     */
static volatile int count1 = 0;   /* refreshes the value every ~0.33 s    */
static int display_value   = 0;

/* Button debounce */
static volatile int  counter20 = 0;
static volatile bool flag2     = false;  /* a press happened              */
static volatile bool flag20    = false;  /* debounce time has passed      */
static int flagbutton = SHOW_VRMS;

/* ------------------------------------------------------------------------- */

void App_Start(void)
{
    HAL_TIM_Base_Start(&htim3);      // Start timer (triggers ADC)
    HAL_ADC_Start_IT(&hadc1);        // Enable ADC with interrupt
    HAL_TIM_Base_Start_IT(&htim2);   // Display multiplexing + timing

    HAL_TIM_Base_Start(&htim4);      // PWM for the negative supply
    HAL_TIM_PWM_Start(&htim4, TIM_CHANNEL_2);
}

void App_Loop(void)
{
    int duty = 1000;
    __HAL_TIM_SET_COMPARE(&htim4, TIM_CHANNEL_2, duty);

    /* Button: accept one press after the debounce delay */
    if (flag20 == true && flag2 == true) {
        flag2 = false;
        if (HAL_GPIO_ReadPin(button_GPIO_Port, button_Pin) == GPIO_PIN_RESET) {
            flagbutton += 1;
            flagbutton = flagbutton % SHOW_COUNT;
            count = 0;
        }
    }

    /* After a press, show the mode number (1..7) for about one second.
     * (Reconstructed from the report's description.) */
    if (count < 200) {
        DisplayNumber(flagbutton + 1);
        return;
    }

    /* Then show the selected quantity, refreshed every ~0.33 s */
    if (count1 >= 59) {
        if (flagbutton == SHOW_VRMS)
            display_value = rms_voltage_ac * 10;
        else if (flagbutton == SHOW_IRMS)
            display_value = rms_current_ac * 100;
        else if (flagbutton == SHOW_FREQ)
            display_value = freq;
        else if (flagbutton == SHOW_PF) {
            float t = cos(phase);
            if (t < 0) t = t * (-1);
            display_value = t * 100;
        }
        else if (flagbutton == SHOW_P)
            display_value = power() * 100;
        else if (flagbutton == SHOW_Q)
            display_value = Q() * 100;
        else if (flagbutton == SHOW_S)
            display_value = S() * 100;

        DisplayNumber(display_value);
        count1 = 0;
    }
}

/* ------------------------------------------------------------------------- */
/* Interrupt callbacks                                                        */
/* ------------------------------------------------------------------------- */

/* ADC1 conversion complete: process the sample, then switch channel so the
 * next TIM3 trigger converts the other signal. Converting one channel at a
 * time (rank 1 only) removed the cross-talk seen in scan mode. */
void HAL_ADC_ConvCpltCallback(ADC_HandleTypeDef *hadc)
{
    if (hadc->Instance == ADC1) {
        raw_value = HAL_ADC_GetValue(hadc);

        if (c == 0) {
            ACM_ProcessVoltageSample(raw_value);
            sConfig.Channel = ADC_CHANNEL_2;
            c = 1;
        } else if (c == 1) {
            ACM_ProcessCurrentSample(raw_value);
            sConfig.Channel = ADC_CHANNEL_1;
            c = 0;
        }

        sConfig.Rank = ADC_REGULAR_RANK_1;
        sConfig.SamplingTime = ADC_SAMPLETIME_55CYCLES_5;
        HAL_ADC_ConfigChannel(hadc, &sConfig);
        HAL_ADC_Start_IT(hadc);
    }
}

/* TIM2 (180 Hz): display multiplexing and all slow timing. */
void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim)
{
    if (htim->Instance == TIM2) {
        Display_Refresh();

        counter20 += 1;
        if (counter20 == 6) {       /* ~33 ms after the press */
            counter20 = 0;
            flag20 = true;
        }

        if (count < 200) count += 1;
        if (count1 < 60) { count1 += 1; }
    }
}

/* Button press (EXTI, falling edge): start the debounce timer instead of
 * blocking with HAL_Delay(). */
void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin)
{
    (void)GPIO_Pin;
    counter20 = 0;
    flag2  = true;
    flag20 = false;
}
